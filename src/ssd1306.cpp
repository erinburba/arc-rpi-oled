static_assert(sizeof(kFont) / sizeof(kFont[0]) == 95);

void blit_glyph(Ssd1306& display, int x, int y, unsigned char glyph) {
  const int index = glyph - 0x20;
  for (int column = 0; column < kGlyphWidth; ++column) {
    const std::uint8_t bits = kFont[index][column];
    for (int row = 0; row < kGlyphHeight; ++row) {
      if ((bits & (1u << row)) == 0) {
        continue;
      }
      const int pixel_x = x + column;
      const int pixel_y = y + row;
      if (pixel_x < 0 || pixel_y < 0 || pixel_x >= Ssd1306::kWidth || pixel_y >= Ssd1306::kHeight) {
        continue;
      }
      display.set_pixel(pixel_x, pixel_y, true);
    }
  }
}

